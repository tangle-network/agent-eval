/**
 * Emit the raw-finding wire contract the Python client validates against.
 *
 *   pnpm run contract:finding         — rewrite the contract from the schema
 *   pnpm run contract:finding:check   — fail when the committed file differs
 *
 * TypeScript owns the schema. Python must not keep a hand-written copy of it,
 * because two copies drift and the drift is invisible: Python reports a
 * completed investigation whose rows TypeScript then drops. The check runs in
 * `verify:package` and in CI, so a schema change that does not regenerate the
 * contract fails before it can ship.
 */

import { readFileSync, writeFileSync } from 'node:fs'
import { resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { z } from 'zod'
import { FINDING_WIRE_CONTRACT_VERSION, MAX_FINDING_ROWS } from '../src/analyst/finding-codec'
import { FINDING_SUBJECT_PATTERNS } from '../src/analyst/finding-subject'
import { RawAnalystFindingSchema } from '../src/analyst/finding-signature'

const repoRoot = fileURLToPath(new URL('..', import.meta.url))
const contractPath = resolve(repoRoot, 'clients/python/src/agent_eval_rpc/finding_contract.json')
const checkMode = process.argv.includes('--check')

const contract = {
  $comment:
    'Generated by scripts/emit-finding-contract.ts from the TypeScript schema. Do not edit by hand.',
  version: FINDING_WIRE_CONTRACT_VERSION,
  maxRows: MAX_FINDING_ROWS,
  row: z.toJSONSchema(RawAnalystFindingSchema, { target: 'draft-7' }),
  // Acceptance only: the typed components parseFindingSubject extracts are
  // consumed by TypeScript adapters and never cross the boundary.
  subjectPatterns: FINDING_SUBJECT_PATTERNS.map((entry) => ({
    kind: entry.kind,
    pattern: entry.pattern,
  })),
}

const rendered = `${JSON.stringify(contract, null, 2)}\n`

if (checkMode) {
  let committed: string
  try {
    committed = readFileSync(contractPath, 'utf8')
  } catch {
    console.error(
      `finding contract is missing: ${contractPath}\nRun: pnpm run contract:finding`,
    )
    process.exit(1)
  }
  if (committed !== rendered) {
    console.error(
      'finding contract is stale: the committed file does not match the TypeScript schema.\n' +
        'Python validates findings against this file, so a stale copy means the two languages ' +
        'accept different rows.\nRun: pnpm run contract:finding',
    )
    process.exit(1)
  }
  console.log(
    `finding contract is fresh: version ${contract.version}, ` +
      `${contract.subjectPatterns.length} subject patterns`,
  )
} else {
  writeFileSync(contractPath, rendered, 'utf8')
  console.log(
    `wrote ${contractPath} (version ${contract.version}, ` +
      `${contract.subjectPatterns.length} subject patterns)`,
  )
}
